<?php
session_start();
// Check if user is logged in and is an admin
if (!isset($_SESSION['user_id']) || $_SESSION['role_id'] != 1) {
    header("Location: login.php");
    exit();
}

require_once 'config/database.php';
require_once 'PDFReportGenerator.php'; // Include our PDF report generator class instead of HTML

$database = new Database();
$conn = $database->getConnection();

// Make sure reports directory exists
if (!file_exists('reports')) {
    mkdir('reports', 0755, true);
}

// Initialize variables
$alert = '';
$alert_type = '';

// Pagination variables
$records_per_page = 10; // Number of reports per page
$page = isset($_GET['page']) ? (int)$_GET['page'] : 1; // Current page, default is 1
$offset = ($page - 1) * $records_per_page; // Calculate the offset for SQL LIMIT

// Process form submissions
if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    // Generate report
    if (isset($_POST['generate_report'])) {
        $report_name = trim($_POST['report_name']);
        $report_type = $_POST['report_type'];
        $date_start = $_POST['date_start'];
        $date_end = $_POST['date_end'];
        
        // Generate report file - now using PDF instead of HTML
        $filename = strtolower(str_replace(' ', '_', $report_name)) . '_' . date('Ymd_His') . '.pdf';
        $file_path = 'reports/' . $filename;
        
        // Store parameters as JSON
        $parameters = json_encode([
            'date_start' => $date_start,
            'date_end' => $date_end,
            'include_appointments' => isset($_POST['include_appointments']) ? 1 : 0,
            'include_services' => isset($_POST['include_services']) ? 1 : 0,
            'include_new_users' => isset($_POST['include_new_users']) ? 1 : 0,
            'include_user_roles' => isset($_POST['include_user_roles']) ? 1 : 0,
            'include_status' => isset($_POST['include_status']) ? 1 : 0,
            'include_dentists' => isset($_POST['include_dentists']) ? 1 : 0
        ]);
        
        // Generate the PDF report
        try {
            // Create new PDFReportGenerator instance
            $report = new PDFReportGenerator($report_name);
            
            // Add header info
            $report->addHeader(ucfirst($report_type) . ' Report', [
                'Date Range' => date('M d, Y', strtotime($date_start)) . ' to ' . date('M d, Y', strtotime($date_end)),
                'Generated By' => $_SESSION['username'] ?? 'Admin',
                'Generated On' => date('F d, Y H:i:s')
            ]);
            
            // Add content based on report type
            switch ($report_type) {
                case 'operational':
                    // Add Operational Report sections
                    $report->addSection('Operational Overview');
                    $report->addParagraph('This report provides an overview of operational metrics between ' . 
                        date('M d, Y', strtotime($date_start)) . ' and ' . date('M d, Y', strtotime($date_end)) . '.');
                    
                    if (isset($_POST['include_appointments'])) {
                        $report->addSubsection('Appointments Summary');
                        
                        // Get appointment data from database with better error handling
                        try {
                            $stmt = $conn->prepare("SELECT status, COUNT(*) as count FROM appointment 
                                                  WHERE appointment_date BETWEEN :date_start AND :date_end 
                                                  GROUP BY status");
                            $stmt->bindParam(':date_start', $date_start);
                            $stmt->bindParam(':date_end', $date_end);
                            $stmt->execute();
                            $appointment_data = $stmt->fetchAll(PDO::FETCH_ASSOC);
                            
                            // Add data to report
                            if (!empty($appointment_data)) {
                                $report->addTable(['Status', 'Count'], array_map(function($row) {
                                    return [$row['status'], $row['count']];
                                }, $appointment_data));
                                
                                // Calculate total appointments
                                $total_appointments = array_sum(array_column($appointment_data, 'count'));
                                $report->addParagraph('Total Appointments: ' . $total_appointments);
                            } else {
                                $report->addParagraph('No appointment data available for the selected period.');
                            }
                        } catch (PDOException $e) {
                            $report->addParagraph('Error retrieving appointment data: ' . $e->getMessage());
                        }
                    }
                    
                    if (isset($_POST['include_services'])) {
                        $report->addSubsection('Services Utilization');
                        
                        // Get service data from database with better error handling
                        try {
                            $stmt = $conn->prepare("SELECT s.service_name, COUNT(a.appointment_id) as usage_count 
                                                  FROM service s
                                                  LEFT JOIN appointment a ON s.service_id = a.service_id AND
                                                       a.appointment_date BETWEEN :date_start AND :date_end 
                                                  GROUP BY s.service_id
                                                  ORDER BY usage_count DESC");
                            $stmt->bindParam(':date_start', $date_start);
                            $stmt->bindParam(':date_end', $date_end);
                            $stmt->execute();
                            $service_data = $stmt->fetchAll(PDO::FETCH_ASSOC);
                            
                            // Add data to report
                            if (!empty($service_data)) {
                                $report->addTable(['Service Name', 'Usage Count'], array_map(function($row) {
                                    return [$row['service_name'], $row['usage_count']];
                                }, $service_data));
                            } else {
                                $report->addParagraph('No service utilization data available for the selected period.');
                            }
                        } catch (PDOException $e) {
                            $report->addParagraph('Error retrieving service data: ' . $e->getMessage());
                        }
                    }
                    break;
                    
                case 'user':
                    // Add User Report sections
                    $report->addSection('User Overview');
                    $report->addParagraph('This report provides user statistics between ' . 
                        date('M d, Y', strtotime($date_start)) . ' and ' . date('M d, Y', strtotime($date_end)) . '.');
                    
                    if (isset($_POST['include_user_roles'])) {
                        $report->addSubsection('User Role Distribution');
                        
                        try {
                            // Check which role table exists
                            $tableResults = [];
                            $tables = ['userrole', 'user_roles', 'role'];
                            
                            foreach ($tables as $table) {
                                $tableStmt = $conn->prepare("SHOW TABLES LIKE :table");
                                $tableStmt->bindParam(':table', $table);
                                $tableStmt->execute();
                                if ($tableStmt->rowCount() > 0) {
                                    $tableResults[$table] = true;
                                }
                            }
                            
                            if (isset($tableResults['userrole'])) {
                                // UseRole table exists
                                $stmt = $conn->prepare("SELECT ur.role_name, COUNT(u.user_id) as count 
                                                     FROM userrole ur
                                                     LEFT JOIN user u ON ur.role_id = u.role_id
                                                     AND (u.created_at BETWEEN :date_start AND :date_end OR u.created_at IS NULL)
                                                     GROUP BY ur.role_id
                                                     ORDER BY count DESC");
                                $stmt->bindParam(':date_start', $date_start);
                                $stmt->bindParam(':date_end', $date_end);
                                $stmt->execute();
                                $role_data = $stmt->fetchAll(PDO::FETCH_ASSOC);
                            } elseif (isset($tableResults['role'])) {
                                // Role table exists
                                $stmt = $conn->prepare("SELECT r.role_name, COUNT(u.user_id) as count 
                                                     FROM role r
                                                     LEFT JOIN user u ON r.role_id = u.role_id
                                                     AND (u.created_at BETWEEN :date_start AND :date_end OR u.created_at IS NULL)
                                                     GROUP BY r.role_id
                                                     ORDER BY count DESC");
                                $stmt->bindParam(':date_start', $date_start);
                                $stmt->bindParam(':date_end', $date_end);
                                $stmt->execute();
                                $role_data = $stmt->fetchAll(PDO::FETCH_ASSOC);
                            } elseif (isset($tableResults['user_roles'])) {
                                // Use user_roles table instead
                                $stmt = $conn->prepare("SELECT ur.role_name, COUNT(u.user_id) as count 
                                                     FROM user_roles ur
                                                     LEFT JOIN user u ON ur.role_id = u.role_id
                                                     AND (u.created_at BETWEEN :date_start AND :date_end OR u.created_at IS NULL)
                                                     GROUP BY ur.role_id
                                                     ORDER BY count DESC");
                                $stmt->bindParam(':date_start', $date_start);
                                $stmt->bindParam(':date_end', $date_end);
                                $stmt->execute();
                                $role_data = $stmt->fetchAll(PDO::FETCH_ASSOC);
                            } else {
                                // Fallback to just getting roles directly from user table
                                $stmt = $conn->prepare("SELECT 
                                                     CASE 
                                                        WHEN role_id = 1 THEN 'Admin'
                                                        WHEN role_id = 2 THEN 'Dentist'
                                                        WHEN role_id = 3 THEN 'Patient'
                                                        ELSE CONCAT('Role ', role_id)
                                                     END as role_name,
                                                     COUNT(user_id) as count
                                                     FROM user
                                                     WHERE (created_at BETWEEN :date_start AND :date_end OR created_at IS NULL)
                                                     GROUP BY role_id
                                                     ORDER BY count DESC");
                                $stmt->bindParam(':date_start', $date_start);
                                $stmt->bindParam(':date_end', $date_end);
                                $stmt->execute();
                                $role_data = $stmt->fetchAll(PDO::FETCH_ASSOC);
                            }
                            
                            if (!empty($role_data)) {
                                $report->addTable(['Role', 'Count'], array_map(function($row) {
                                    return [$row['role_name'], $row['count']];
                                }, $role_data));
                            } else {
                                $report->addParagraph('No user role data available.');
                            }
                        } catch (PDOException $e) {
                            $report->addParagraph('Error retrieving user role data: ' . $e->getMessage());
                        }
                    }
                    
                    if (isset($_POST['include_new_users'])) {
                        $report->addSubsection('New User Registrations');
                        
                        try {
                            // Get new users by day
                            $stmt = $conn->prepare("SELECT DATE(created_at) as date, COUNT(*) as count 
                                                  FROM user 
                                                  WHERE created_at BETWEEN :date_start AND :date_end 
                                                  GROUP BY DATE(created_at)
                                                  ORDER BY date");
                            $stmt->bindParam(':date_start', $date_start);
                            $stmt->bindParam(':date_end', $date_end);
                            $stmt->execute();
                            $new_users_data = $stmt->fetchAll(PDO::FETCH_ASSOC);
                            
                            if (!empty($new_users_data)) {
                                $report->addTable(['Date', 'New Users'], array_map(function($row) {
                                    return [date('M d, Y', strtotime($row['date'])), $row['count']];
                                }, $new_users_data));
                                
                                // Calculate total new users
                                $total_new_users = array_sum(array_column($new_users_data, 'count'));
                                $report->addParagraph('Total New Users: ' . $total_new_users);
                            } else {
                                $report->addParagraph('No new user registrations during the selected period.');
                            }
                        } catch (PDOException $e) {
                            $report->addParagraph('Error retrieving new user data: ' . $e->getMessage());
                        }
                    }
                    break;
                    
                case 'appointment':
                    // Appointment reports implementation
                    $report->addSection('Appointment Statistics');
                    $report->addParagraph('This report provides appointment statistics between ' . 
                        date('M d, Y', strtotime($date_start)) . ' and ' . date('M d, Y', strtotime($date_end)) . '.');
                    
                    if (isset($_POST['include_status'])) {
                        $report->addSubsection('Appointment Status Breakdown');
                        
                        try {
                            // Get status breakdown
                            $stmt = $conn->prepare("SELECT status, COUNT(*) as count 
                                                 FROM appointment 
                                                 WHERE appointment_date BETWEEN :date_start AND :date_end 
                                                 GROUP BY status");
                            $stmt->bindParam(':date_start', $date_start);
                            $stmt->bindParam(':date_end', $date_end);
                            $stmt->execute();
                            $status_data = $stmt->fetchAll(PDO::FETCH_ASSOC);
                            
                            if (!empty($status_data)) {
                                $report->addTable(['Status', 'Count'], array_map(function($row) {
                                    return [$row['status'], $row['count']];
                                }, $status_data));
                                
                                // Calculate total appointments
                                $total_appointments = array_sum(array_column($status_data, 'count'));
                                $report->addParagraph('Total Appointments: ' . $total_appointments);
                            } else {
                                $report->addParagraph('No appointment data available for the selected period.');
                            }
                        } catch (PDOException $e) {
                            $report->addParagraph('Error retrieving appointment status data: ' . $e->getMessage());
                        }
                    }
                    
                    if (isset($_POST['include_dentists'])) {
                        $report->addSubsection('Dentist Appointment Load');
                        
                        try {
                            // Get dentist load
                            $stmt = $conn->prepare("SELECT u.username as dentist_name, COUNT(a.appointment_id) as appointment_count 
                                                 FROM user u
                                                 LEFT JOIN appointment a ON u.user_id = a.dentist_id
                                                    AND a.appointment_date BETWEEN :date_start AND :date_end
                                                 WHERE u.role_id = 2
                                                 GROUP BY u.user_id
                                                 ORDER BY appointment_count DESC");
                            $stmt->bindParam(':date_start', $date_start);
                            $stmt->bindParam(':date_end', $date_end);
                            $stmt->execute();
                            $dentist_data = $stmt->fetchAll(PDO::FETCH_ASSOC);
                            
                            if (!empty($dentist_data)) {
                                $report->addTable(['Dentist', 'Appointment Count'], array_map(function($row) {
                                    return [$row['dentist_name'], $row['appointment_count']];
                                }, $dentist_data));
                            } else {
                                $report->addParagraph('No dentist appointment data available for the selected period.');
                            }
                        } catch (PDOException $e) {
                            $report->addParagraph('Error retrieving dentist appointment data: ' . $e->getMessage());
                        }
                    }
                    break;
                
                default:
                    throw new Exception("Invalid report type selected.");
            }
            
            // Add footer
            $report->addFooter('This report was automatically generated by JRC Dental Care Management System.');
            
            // Save PDF file
            if ($report->saveToFile($file_path)) {
                // Insert record into database
                $stmt = $conn->prepare("INSERT INTO report (report_name, report_type, generated_by, file_path, parameters) VALUES (:report_name, :report_type, :generated_by, :file_path, :parameters)");
                $stmt->bindParam(':report_name', $report_name);
                $stmt->bindParam(':report_type', $report_type);
                $stmt->bindParam(':generated_by', $_SESSION['user_id']);
                $stmt->bindParam(':file_path', $file_path);
                $stmt->bindParam(':parameters', $parameters);
                
                if ($stmt->execute()) {
                    // Log to audit trail
                    $audit_stmt = $conn->prepare("INSERT INTO audittrail (user_id, action_performed, table_affected, details) VALUES (:user_id, 'GENERATE', 'report', :details)");
                    $audit_stmt->bindParam(':user_id', $_SESSION['user_id']);
                    $details = "Generated report: " . $report_name;
                    $audit_stmt->bindParam(':details', $details);
                    $audit_stmt->execute();
                    
                    // Redirect to avoid form resubmission
                    header("Location: reports.php?success=1");
                    exit();
                }
            } else {
                $alert = "Error saving report file.";
                $alert_type = "danger";
            }
        } catch (Exception $e) {
            $alert = "Error generating report: " . $e->getMessage();
            $alert_type = "danger";
        }
    }
    
    // Delete report
    if (isset($_POST['delete_report'])) {
        $report_id = $_POST['report_id'];
        
        try {
            // Get file path before deleting
            $file_stmt = $conn->prepare("SELECT file_path FROM report WHERE report_id = :report_id");
            $file_stmt->bindParam(':report_id', $report_id);
            $file_stmt->execute();
            $file_path = $file_stmt->fetchColumn();
            
            // Delete the report record
            $stmt = $conn->prepare("DELETE FROM report WHERE report_id = :report_id");
            $stmt->bindParam(':report_id', $report_id);
            
            if ($stmt->execute()) {
                // Try to delete the file if it exists
                if (file_exists($file_path)) {
                    unlink($file_path);
                }
                
                // Log to audit trail
                $audit_stmt = $conn->prepare("INSERT INTO audittrail (user_id, action_performed, table_affected, details) VALUES (:user_id, 'DELETE', 'report', :details)");
                $audit_stmt->bindParam(':user_id', $_SESSION['user_id']);
                $details = "Deleted report ID: " . $report_id;
                $audit_stmt->bindParam(':details', $details);
                $audit_stmt->execute();
                
                $alert = "Report deleted successfully.";
                $alert_type = "success";
            }
        } catch (PDOException $e) {
            $alert = "Error: " . $e->getMessage();
            $alert_type = "danger";
        }
    }
}

// Success message from redirect
if (isset($_GET['success'])) {
    $alert = "Report generated successfully. You can download it from the reports list.";
    $alert_type = "success";
}

// Get total number of reports for pagination
$count_stmt = $conn->prepare("SELECT COUNT(*) as total FROM report");
$count_stmt->execute();
$total_records = $count_stmt->fetch(PDO::FETCH_ASSOC)['total'];
$total_pages = ceil($total_records / $records_per_page);

// Get reports with pagination
